"""Builds the Hebrew translation data from tools/hebrew/*.txt.

    python3 tools/hebrew_build.py          # writes the files, prints untranslated strings

Writes MathAlarm/Resources/hebrew.json (used by L() at runtime) and
MathAlarm/Resources/he.lproj/Localizable.strings (for SwiftUI literals).
"""
import glob, itertools, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import strings_scan  # noqa: E402

def load():
    table = {}
    for path in sorted(glob.glob(os.path.join(ROOT, "tools", "hebrew", "*.txt"))):
        for n, line in enumerate(open(path, encoding="utf-8"), 1):
            line = line.rstrip("\n")
            if not line.strip() or line.lstrip().startswith("#"): continue
            if " ⟹ " not in line:
                print(f"{os.path.basename(path)}:{n}: no ⟹", file=sys.stderr); continue
            en, he = line.split(" ⟹ ", 1)
            en, he = en.replace("\\n", "\n"), he.replace("\\n", "\n")
            if en.strip() != en and en.strip() and en[0].isalpha():
                en = en.rstrip()
            table[en] = he
    return table

def placeholders(he):
    """Hebrew template -> list of 0-based capture indices in order."""
    out, seq = [], 0
    for m in re.finditer(r"\{(\d*)\}", he):
        if m.group(1): out.append(int(m.group(1)) - 1)
        else: out.append(seq); seq += 1
    return out

def main():
    table = load()
    exact, templates, phrases = {}, [], []
    for en, he in table.items():
        if "{}" in en:
            if not re.search(r"[A-Za-z]{2,}", en.replace("{}", "")): continue
            templates.append([en.strip(), he.strip()])
        elif en[:1] in " ,—-;(" or en.endswith(" "):
            phrases.append([en, he])
        else:
            exact[en] = he
            if len(en.split()) >= 2 or len(en) >= 8:
                phrases.append([en, he])
    # More literal text first: the most specific template wins.
    templates.sort(key=lambda t: -len(t[0].replace("{}", "")))
    phrases.sort(key=lambda p: -len(p[0]))
    res = os.path.join(ROOT, "MathAlarm", "Resources")
    with open(os.path.join(res, "hebrew.json"), "w", encoding="utf-8") as f:
        json.dump({"exact": exact, "templates": templates, "phrases": phrases}, f, ensure_ascii=False, indent=0)

    # Localizable.strings: exact keys, plus format-key variants of the templates for interpolated literals.
    os.makedirs(os.path.join(res, "he.lproj"), exist_ok=True)
    def q(s): return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'
    lines = []
    for en, he in sorted(exact.items()):
        lines.append(f"{q(en)} = {q(he)};")
    seen = set(exact)
    for en, he in templates:
        n = en.count("{}")
        if n > 3: continue
        order = placeholders(he)
        for specs in itertools.product(["%@", "%lld"], repeat=n):
            key = en.replace("%", "%%")
            for s in specs: key = key.replace("{}", s, 1)
            if key in seen: continue
            seen.add(key)
            val, i = he, 0
            def sub(m):
                nonlocal i
                idx = int(m.group(1)) - 1 if m.group(1) else order[i]
                i += 1
                return f"%{idx + 1}${specs[idx][1:]}" if idx < n else ""
            val = re.sub(r"\{(\d*)\}", sub, he.replace("%", "%%"))
            lines.append(f"{q(key)} = {q(val)};")
    with open(os.path.join(res, "he.lproj", "Localizable.strings"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/hebrew_build.py — edit tools/hebrew/*.txt instead. */\n")
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(res, "he.lproj", "InfoPlist.strings"), "w", encoding="utf-8") as f:
        f.write('"CFBundleDisplayName" = "Math Alarm β";\n')

    # Coverage: strings in the code that nothing translates.
    compiled = [re.compile("".join("(.*?)" if part == "{}" else re.escape(part) for part in re.split(r"(\{\})", t[0])), re.S)
                for t in templates]
    known = set(exact) | {t[0] for t in templates} | {p[0].strip() for p in phrases}
    missing = []
    for path in sorted(glob.glob(os.path.join(ROOT, "MathAlarm", "**", "*.swift"), recursive=True)) + \
                sorted(glob.glob(os.path.join(ROOT, "Packages", "MathEngine", "Sources", "MathEngine", "*.swift"))):
        for call, text, parts in strings_scan.scan(open(path, encoding="utf-8").read()):
            if not strings_scan.needs_translation(text): continue
            k = text.replace("\u0001", "{}").strip()
            if k in known or not re.search(r"[A-Za-z]{3,}", k): continue
            if re.fullmatch(r"[a-z]+:.*", k) or k.isupper(): continue          # ids, letter lists
            if any(rx.fullmatch(k.replace("{}", "1")) for rx in compiled): continue
            missing.append((os.path.basename(path), k))
    print(f"{len(exact)} exact, {len(templates)} templates, {len(phrases)} phrases; {len(missing)} strings not covered")
    if "-v" in sys.argv:
        for f, k in missing: print(f"  {f}: {k[:110]!r}")

if __name__ == "__main__":
    main()
